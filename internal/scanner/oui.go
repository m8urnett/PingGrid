// NormalizeMAC normalizes a MAC address string to lower-case colon-separated format (e.g. "00:15:5d:00:62:1b").
// Returns an empty string if the MAC cannot be parsed into 6 octets.
func NormalizeMAC(mac string) string {
	clean := strings.TrimSpace(strings.ToLower(mac))
	clean = strings.ReplaceAll(clean, "-", "")
	clean = strings.ReplaceAll(clean, ":", "")
	clean = strings.ReplaceAll(clean, ".", "")
	if len(clean) != 12 {
		return ""
	}
	var b strings.Builder
	for i := 0; i < 12; i += 2 {
		if i > 0 {
			b.WriteByte(':')
		}
		b.WriteString(clean[i : i+2])
	}
	return b.String()
}

// ExtractOUIPrefix returns the 6-character hex prefix (24-bit OUI) in lower case without separators.
func ExtractOUIPrefix(mac string) string {
	clean := strings.TrimSpace(strings.ToLower(mac))
	clean = strings.ReplaceAll(clean, "-", "")
	clean = strings.ReplaceAll(clean, ":", "")
	clean = strings.ReplaceAll(clean, ".", "")
	if len(clean) >= 6 {
		return clean[:6]
	}
	return ""
}

// LookupVendor returns the manufacturer / vendor name for a given MAC address.
// Returns an empty string if unknown.
func LookupVendor(mac string) string {
	prefix := ExtractOUIPrefix(mac)
	if prefix == "" {
		return ""
	}
	if v, ok := ouiVendors[prefix]; ok {
		return v
	}
	return ""
}

